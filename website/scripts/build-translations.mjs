import {readFileSync,writeFileSync} from 'node:fs';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const site=join(dirname(fileURLToPath(import.meta.url)),'..');
const sources=JSON.parse(readFileSync(join(site,'locales/source.json'),'utf8'));
const catalogs={};
const problems=[];
for(const lang of ['ja','ko','es','fr']) {
 const catalog=JSON.parse(readFileSync(join(site,'locales',`${lang}.json`),'utf8'));
 for(const {en} of sources) {
  if(typeof catalog[en]!=='string' || !catalog[en].trim()) {problems.push(`${lang}: missing ${en}`);continue;}
  const placeholders=s=>[...s.matchAll(/\{[a-zA-Z]+\}/g)].map(m=>m[0]).sort().join(',');
  if(placeholders(en)!==placeholders(catalog[en]))problems.push(`${lang}: placeholder mismatch ${en}`);
 }
 catalogs[lang]=catalog;
}
if(problems.length)throw new Error(problems.join('\n'));
writeFileSync(join(site,'assets/translations.js'),`// Generated by scripts/build-translations.mjs from locales/*.json.\nwindow.RM_TRANSLATIONS = ${JSON.stringify(catalogs).replaceAll('<','\\u003c')};\n`);
console.log(`Built four catalogs; ${sources.length} source strings per language checked.`);
