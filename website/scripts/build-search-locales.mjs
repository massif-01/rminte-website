import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runInNewContext } from 'node:vm';
import { parse, parseFragment, serialize, defaultTreeAdapter as tree } from 'parse5';
import { englishPages, pages, searchFiles, seoHead } from './seo.mjs';

const site = fileURLToPath(new URL('../', import.meta.url));
const englishPaths = new Map(Object.keys(englishPages).map(key => [pages[key].path, englishPages[key].path]));
const browserData = { window: {} };
runInNewContext(readFileSync(join(site, 'assets/site-data.js'), 'utf8'), browserData);
const { nav, ui } = browserData.window.RM_SOFT;

const attr = (node, name) => node.attrs.find(attribute => attribute.name === name)?.value;
function setAttr(node, name, value) {
  const attribute = node.attrs.find(item => item.name === name);
  if (attribute) attribute.value = value;
  else node.attrs.push({ name, value });
}

function setText(node, value) {
  node.childNodes = [];
  tree.insertText(node, value);
}

function englishLink(href, sourcePath) {
  if (!href || href.startsWith('#')) return href;
  const base = new URL(sourcePath, 'https://local.invalid');
  const target = new URL(href, base);
  if (target.origin !== base.origin) return href;
  const path = target.pathname.replace(/index\.html$/, '');
  return englishPaths.has(path) ? englishPaths.get(path) + target.search + target.hash : href;
}

function localize(document, page) {
  function visit(node) {
    if (node.tagName) {
      const uiKey = attr(node, 'data-ui') ?? attr(node, 'data-footer-text');
      const translation = uiKey === undefined ? attr(node, 'data-en') : ui.en[uiKey];
      if (uiKey !== undefined && translation === undefined) throw new Error(`Missing English copy: ${uiKey}`);
      for (const { name, value } of [...node.attrs]) {
        const match = name.match(/^data-i18n-(.+)-en$/);
        if (match) setAttr(node, match[1], value);
      }

      if (node.tagName === 'html') {
        setAttr(node, 'lang', 'en');
        setAttr(node, 'data-search-language', 'en');
        setAttr(node, 'data-search-paths', JSON.stringify([...englishPaths]));
      } else if (node.tagName === 'script') {
        const src = attr(node, 'src');
        if (src?.includes('assets/i18n.js?')) setAttr(node, 'src', src.replace(/\?.*$/, '?v=search-locale-1'));
        // Match the same priority as i18n.js before fetching a catalog or font.
        const bootstrap = node.childNodes[0];
        if (bootstrap?.value.includes('window.RM_CATALOG =')) {
          const languageFallback = 's, window.RM_DEFAULT_LANG';
          if (!bootstrap.value.includes(languageFallback)) throw new Error(`Localize the catalog bootstrap in ${page.file}`);
          bootstrap.value = bootstrap.value.replace(languageFallback, 'document.documentElement.dataset.searchLanguage, ' + languageFallback);
        }
      } else if (node.tagName === 'a' && attr(node, 'href')) {
        setAttr(node, 'href', englishLink(attr(node, 'href'), page.path));
      }

      if (attr(node, 'data-hero-title') !== undefined) {
        node.childNodes = [];
        for (const line of ui.en.heroTitle.split('\n')) {
          const fragment = parseFragment('<span class="hero-title-line" data-enter="line"><span class="line-in"></span></span>');
          const [outer] = fragment.childNodes;
          tree.insertText(outer.childNodes[0], line);
          tree.appendChild(node, outer);
        }
      } else if (['desktopNav', 'mobileNav'].includes(attr(node, 'id'))) {
        for (const [id, label, options] of nav) {
          const link = tree.createElement('a', node.namespaceURI, [{ name: 'href', value: englishLink(options?.href || `#${id}`, page.path) }]);
          tree.insertText(link, label.en);
          tree.appendChild(node, link);
        }
      } else if (translation !== undefined && !['meta', 'script', 'title'].includes(node.tagName)) {
        setText(node, translation);
      }
    }
    for (const child of node.childNodes || []) visit(child);
  }
  visit(document);
}

function englishPage(key, page) {
  const source = readFileSync(join(site, page.file), 'utf8');
  const head = /<!-- SEO:[\s\S]*?<!-- \/SEO -->/;
  if (!head.test(source)) throw new Error(`Missing SEO metadata in ${page.file}`);
  const document = parse(source.replace(head, () => seoHead(key, 'en')));
  localize(document, page);
  return '<!-- Generated by scripts/build-search-locales.mjs from ' + page.file + '. -->\n' + serialize(document) + '\n';
}

function writeOutput(file, content, check) {
  const path = join(site, file);
  if (check) {
    if (readFileSync(path, 'utf8') !== content) throw new Error(`${file} is stale. Run node website/scripts/build-search-locales.mjs.`);
  } else {
    writeFileSync(path, content);
  }
}

export function buildEnglishPages(check) {
  for (const [key, page] of Object.entries(englishPages)) writeOutput(page.file, englishPage(key, pages[key]), check);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  buildEnglishPages(check);
  for (const [file, content] of Object.entries(searchFiles())) writeOutput(file, content, check);
  console.log(`${check ? 'Checked' : 'Generated'} English search pages, sitemap and robots.txt.`);
}
