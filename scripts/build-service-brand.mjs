import {readFile,writeFile} from 'node:fs/promises';
const root = new URL('../',import.meta.url);
const css = (await readFile(new URL('website/assets/brand.css',root),'utf8')).replaceAll('url("fonts/', 'url("https://rminte.com/assets/fonts/');
const logo = (await readFile(new URL('website/assets/images/logo-white.svg',root),'utf8')).replace(/<\?xml[^>]*>/g,'');
const output = '// Generated by scripts/build-service-brand.mjs. Do not edit.\nexport const brandCSS = '+JSON.stringify(css)+';\nexport const brandLogo = '+JSON.stringify(logo)+';\n';
const target = new URL('services/tianshanos-ota/src/brand.generated.js',root);
if(process.argv.includes('--check')) {
 if(await readFile(target,'utf8') !== output) throw new Error('Service brand assets are stale. Run node scripts/build-service-brand.mjs');
} else await writeFile(target,output);
